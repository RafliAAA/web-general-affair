async function main() {
  console.log("Mulai proses seeding aset...");

  for (const catData of categoriesToSeed) {
    await prisma.$transaction(async (tx) => {
      // 1. Cari atau buat kategori
      const category = await tx.assetCategory.upsert({
        where: { category_code: catData.code },
        update: { category_name: catData.name },
        create: { category_name: catData.name, category_code: catData.code },
      });

      console.log(
        `Membuat ${catData.count} aset untuk kategori: ${catData.name}...`,
      );

      // 2. Cari nomor urut aset terakhir untuk kategori ini
      const searchPrefix = `AST-${catData.code}`;
      const lastAsset = await tx.asset.findFirst({
        where: { asset_code: { startsWith: searchPrefix } },
        orderBy: { asset_code: "desc" },
        select: { asset_code: true },
      });

      let lastNum = 0;
      if (lastAsset?.asset_code) {
        // Ambil 4 digit terakhir (SAMA PERSIS dengan logika aplikasimu)
        const last4Digits = lastAsset.asset_code.slice(-4);
        lastNum = parseInt(last4Digits, 10) || 0;
      }

      const nameList = realisticAssetNames[catData.code] || ["Aset Umum"];

      // 3. Siapkan data aset untuk di-create (Bulk Insert)
      const assetsToCreate = [];
      for (let i = 1; i <= catData.count; i++) {
        lastNum += 1;
        const assetCode = `${searchPrefix}${String(lastNum).padStart(4, "0")}`;

        // Ambil nama dari list. Karena panjang list sudah disesuaikan, tidak akan berulang.
        const baseName = nameList[(i - 1) % nameList.length];
        const assetName = baseName;

        // Buat tanggal pembelian dan garansi
        const purchaseDate = new Date();
        const warrantyDate = new Date(purchaseDate);
        // Garansi acak 1 atau 2 tahun dari tanggal pembelian
        warrantyDate.setFullYear(
          warrantyDate.getFullYear() + (Math.random() > 0.5 ? 1 : 2),
        );

        assetsToCreate.push({
          asset_code: assetCode,
          asset_name: assetName,
          asset_category_id: category.asset_category_id,
          serial_number: `SN-${catData.code}-${Date.now()}-${lastNum}`,
          purchase_date: purchaseDate,
          warranty_date: warrantyDate,
          condition: AssetCondition.Baik,
          status: AssetStatus.Tersedia,
        });
      }

      // 4. Eksekusi Bulk Insert
      if (assetsToCreate.length > 0) {
        await tx.asset.createMany({
          data: assetsToCreate,
        });
        console.log(`Selesai membuat ${catData.count} aset ${catData.name}.`);
      }
    });
  }

  console.log("Seeding aset berhasil diselesaikan!");
}

main()
  .catch((e) => {
    console.error("Error saat seeding:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
